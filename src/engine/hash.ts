// Identidade de conteúdo por hash — fonte ÚNICA para Node e navegador.
//
// `canonicalJson` segue o JCS (RFC 8785): chaves ordenadas por unidade de
// código UTF-16, sem espaços, números e strings no formato do JSON.stringify
// do ECMAScript (que é o que o JCS adota). `sha256Hex` é SHA-256 em TypeScript
// puro e SÍNCRONO: `node:crypto` quebraria o bundle do web e `crypto.subtle` é
// assíncrono, o que obrigaria todo chamador a virar async só para hashear. O
// custo é irrelevante nos volumes daqui (itens de biblioteca, prompts, chaves
// de cache).
//
// Usos previstos: contentHash/parentHash de itens curados, hash de dataset e
// de prompt no registro de aprovação, chave do cache de vereditos, formato de
// troca. Mesmo valor nos dois runtimes por construção (sem dependência de
// plataforma).

/** Serialização canônica JCS (RFC 8785). Rejeita o que JSON não representa. */
export function canonicalJson(value: unknown): string {
  if (value === null) return 'null';
  switch (typeof value) {
    case 'boolean':
      return value ? 'true' : 'false';
    case 'number':
      if (!Number.isFinite(value)) throw new TypeError('canonicalJson: número não finito');
      // -0 serializa como 0 (JSON.stringify já faz isso).
      return JSON.stringify(value);
    case 'string':
      return JSON.stringify(value);
    case 'object': {
      if (Array.isArray(value)) {
        return `[${value.map((v) => (v === undefined ? 'null' : canonicalJson(v))).join(',')}]`;
      }
      const obj = value as Record<string, unknown>;
      const keys = Object.keys(obj)
        .filter((k) => obj[k] !== undefined && typeof obj[k] !== 'function')
        .sort(compareUtf16);
      return `{${keys.map((k) => `${JSON.stringify(k)}:${canonicalJson(obj[k])}`).join(',')}}`;
    }
    default:
      throw new TypeError(`canonicalJson: tipo não serializável (${typeof value})`);
  }
}

/** Ordenação por unidade de código UTF-16 (a que o JCS exige). */
function compareUtf16(a: string, b: string): number {
  return a < b ? -1 : a > b ? 1 : 0;
}

